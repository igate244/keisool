// K熱電対 0℃以上の指数補正項
const K_A = [0.1185976, -1.183432e-4, 126.9686];

export const TC_TYPES = Object.keys(TABLE) as TcType[];
export const tcName = (t: TcType) => TABLE[t].name;
export const tcRange = (t: TcType) => TABLE[t].range;

/** B熱電対は約42℃以下で起電力がほぼ0（二価）になるため、逆変換は50℃以上で解く */
export const tcInverseMin = (t: TcType) => (t === 'B' ? 50 : TABLE[t].range[0]);

function poly(c: number[], x: number): number {
  let y = 0;
  for (let i = c.length - 1; i >= 0; i--) y = y * x + c[i];
  return y;
}

/** 温度[℃]→起電力[mV]（基準接点0℃）。範囲外は NaN */
export function tcEmf(type: TcType, t: number): number {
  const d = TABLE[type];
  if (!Number.isFinite(t) || t < d.range[0] - 1e-9 || t > d.range[1] + 1e-9) return NaN;
  const seg = d.segs.find((s) => t < s.hi) ?? d.segs[d.segs.length - 1];
  let e = poly(seg.c, t);
  if (type === 'K' && t >= 0) e += K_A[0] * Math.exp(K_A[1] * (t - K_A[2]) ** 2);
  return e;
}

/** 起電力[mV]（基準接点0℃）→温度[℃]。範囲外は NaN */
export function tcTemp(type: TcType, emf: number): number {
  if (!Number.isFinite(emf)) return NaN;
  let lo = tcInverseMin(type);
  let hi = TABLE[type].range[1];
  const elo = tcEmf(type, lo);
  const ehi = tcEmf(type, hi);
  if (emf < elo - 1e-9 || emf > ehi + 1e-9) return NaN;
  for (let i = 0; i < 200 && hi - lo > 1e-9; i++) {
    const mid = (lo + hi) / 2;
    if (tcEmf(type, mid) < emf) lo = mid;
    else hi = mid;
  }
  return (lo + hi) / 2;
}

/** 冷接点補償つき：測定温度→端子で測れる起電力 */
export function tcMeasuredEmf(type: TcType, t: number, cj: number): number {
  return tcEmf(type, t) - tcEmf(type, cj);
}

/** 冷接点補償つき：端子の起電力→測定温度 */
export function tcTempFromMeasured(type: TcType, emf: number, cj: number): number {
  return tcTemp(type, emf + tcEmf(type, cj));
}
